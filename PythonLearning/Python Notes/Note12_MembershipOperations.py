#Membership operations are used to test whether a value is in or not in a sequence. (List, Tuple, Set, Dictionary, and Strings).

name: str = "Bobby"
print("o" in name) #Will Return True because there is an "o" in Bobby's name.
print("p" in name) #Will return False because there is not a "p" in Bobby's name.

print()

basiclist: list = [1,2,3,4,5]
print(2 in basiclist) #will print true cause 2 is in the list
print(19 in basiclist) #will print false cause 19 is not.

print()

print(19 not in basiclist) #Basically the inverse of in, you can use it to check if something isn't present. #Returns true cause 19 isn't
# in the list.


